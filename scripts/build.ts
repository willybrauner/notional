#!/usr/bin/env node

import { spawn } from 'child_process';
import { mkdirSync, copyFileSync, existsSync, readFileSync, watch } from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import process from 'process';
import esbuild from 'esbuild';
import { builtinModules } from 'node:module';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(__dirname, '..');
const distDir = path.join(projectRoot, 'dist');
const mainScss = path.join(projectRoot, 'styles', 'main.scss');
const outputCss = path.join(distDir, 'styles.css');
const localEnvPath = path.join(projectRoot, '.env.local');
const bin = (name: string) => path.join(projectRoot, 'node_modules/.bin', name);

// Local overrides (not committed): NOTIONAL_PLUGIN_DIR=<vault>/.obsidian/plugins/notionalize
// Plugin folder of the vault the build is copied into; no copy when unset
const obsidianPluginPath = process.env.NOTIONAL_PLUGIN_DIR ?? readLocalEnv('NOTIONAL_PLUGIN_DIR') ?? '';

function readLocalEnv(key: string): string | undefined {
  if (!existsSync(localEnvPath)) return undefined;
  const line = readFileSync(localEnvPath, 'utf8').split('\n').find((l) => l.startsWith(`${key}=`));
  return line?.slice(key.length + 1).trim();
}

const watchMode = process.argv.includes('--watch');

const esbuildExternals = [
  'obsidian', 'electron',
  '@codemirror/autocomplete', '@codemirror/collab', '@codemirror/commands',
  '@codemirror/language', '@codemirror/lint', '@codemirror/search',
  '@codemirror/state', '@codemirror/view',
  '@lezer/common', '@lezer/highlight', '@lezer/lr',
  ...builtinModules,
];

const esbuildBanner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
https://github.com/willybrauner/notionalize (third-party licenses: THIRD_PARTY_NOTICES.md)
*/
`;

function setup(): void {
  mkdirSync(distDir, { recursive: true });
  copyFileSync(path.join(projectRoot, 'manifest.json'), path.join(distDir, 'manifest.json'));
}

function copyToObsidian(files: string[] = ['main.js', 'styles.css', 'manifest.json']): void {
  if (!obsidianPluginPath || process.env.CI) return;
  try {
    mkdirSync(obsidianPluginPath, { recursive: true });
    for (const file of files) {
      copyFileSync(path.join(distDir, file), path.join(obsidianPluginPath, file));
    }

    console.log('✓ Copied to Obsidian');
  } catch {
    // Silently fail if path is not accessible (e.g., in CI)
  }
}

function typeCheck(): Promise<void> {
  return new Promise((resolve, reject) => {
    const child = spawn(bin('tsc'), ['--noEmit', '--skipLibCheck'], {
      cwd: projectRoot,
      stdio: 'inherit',
    });
    child.on('close', (code) => {
      if (code !== 0) reject(new Error('TypeScript type check failed'));
      else resolve();
    });
  });
}

function compileSass(): Promise<void> {
  return new Promise((resolve, reject) => {
    // --no-charset: no BOM in front of a compressed file with non-ASCII characters.
    // Obsidian injects styles.css as text, so a BOM became part of the first selector
    const child = spawn(bin('sass'), ['--no-source-map', '--no-charset', '--style=compressed', mainScss, outputCss], {
      cwd: projectRoot,
      stdio: 'inherit',
    });
    child.on('close', (code) => {
      if (code === 0) {
        console.log('✓ SCSS compiled');
        resolve();
      } else {
        reject(new Error('SCSS compilation failed'));
      }
    });
  });
}

function esbuildBaseConfig(prod: boolean): esbuild.BuildOptions {
  return {
    banner: { js: esbuildBanner },
    entryPoints: ['src/main.ts'],
    bundle: true,
    external: esbuildExternals,
    format: 'cjs',
    target: 'es2018',
    logLevel: 'info',
    sourcemap: prod ? false : 'inline',
    treeShaking: true,
    outfile: 'dist/main.js',
    minify: prod,
  };
}

async function buildOnce(): Promise<void> {
  setup();
  const context = await esbuild.context(esbuildBaseConfig(true));
  try {
    // tsc and esbuild are independent — run in parallel
    await Promise.all([typeCheck(), context.rebuild()]);
  } finally {
    await context.dispose();
  }
  await compileSass();
  copyToObsidian();
}

async function buildWatch(): Promise<void> {
  setup();
  await typeCheck();

  let esbuildReady = false;
  let sassReady = false;
  let resolveInitial!: () => void;
  const initialReady = new Promise<void>((r) => { resolveInitial = r; });
  const checkReady = () => { if (esbuildReady && sassReady) resolveInitial(); };

  const context = await esbuild.context({
    ...esbuildBaseConfig(false),
    plugins: [{
      name: 'notify',
      setup(build) {
        build.onEnd((result) => {
          if (result.errors.length > 0) return;
          if (!esbuildReady) {
            esbuildReady = true;
            checkReady();
          } else {
            try { copyToObsidian(['main.js']); } catch (e) { console.error('✗ Copy failed:', e); }
          }
        });
      },
    }],
  });
  await context.watch();

  // sass --watch handles @use/@import dependency tracking natively
  spawn(bin('sass'), ['--no-source-map', '--no-charset', '--style=compressed', '--watch', `${mainScss}:${outputCss}`], {
    cwd: projectRoot,
    stdio: 'inherit',
  });

  // Watch dist dir for CSS output — reliable since distDir always exists after setup()
  let cssDebounce: ReturnType<typeof setTimeout>;
  watch(distDir, (_event, filename) => {
    if (filename !== 'styles.css') return;
    clearTimeout(cssDebounce);
    cssDebounce = setTimeout(() => {
      if (!sassReady) {
        sassReady = true;
        checkReady();
      } else {
        try { copyToObsidian(['styles.css']); } catch (e) { console.error('✗ Copy failed:', e); }
      }
    }, 50);
  });

  // Wait for both first builds, then do the initial full copy
  await initialReady;
  copyToObsidian();
}

const run = watchMode ? buildWatch() : buildOnce();
run.catch((e: Error) => {
  console.error('✗', e.message);
  process.exit(1);
});
